#!/usr/bin/env bash
# lv-ignored-sources.sh <PLN-NNN> [--worktree <dir>]
#
# Lists the source files a plan wrote that git will never see: present in its
# feature worktree, untracked, and matched by an ignore rule.
#
# WHY THIS EXISTS
#
# A client's PLN-063 put new server code under `src/<App>/Debug/` and client
# code under `client/src/debug/`. The stock .NET `.gitignore` rule `[Dd]ebug/`
# matches both, so not one of those files was ever committed. Verify, test and
# the post-merge suite all passed, because every one of them ran in the feature
# worktree, where the files were on disk. The release then failed to build
# from a clean checkout (CS0234), and removing the worktree at completion
# deleted the only copy. The source was lost (the client's BUG-065).
#
# Nothing in the harness asked whether what the builder wrote is what git
# holds. This does, from the plan's own `**Files:**` lines:
#
#   - every listed path that exists in the worktree, is untracked, and is
#     ignored;
#   - every ignored, untracked file directly inside the directory of a listed
#     path, when it shares an extension with a path listed in THAT directory —
#     the builder's sibling file the plan did not name (DebugReportSetup.cs
#     beside the two it did). Direct children only, so `bin/` and `obj/` under
#     a project directory are not read; the root is skipped, so `.env` is not
#     either. The extensions are per directory, never pooled: a plan listing
#     brainstorm/README.md and surface/index.html flagged brainstorm/*.html,
#     a deliberately ignored build output it never wrote, on seven plans
#     running (a client's LVI-044..LVI-056).
#
# DERIVED FILES — levain.yml `ignoredSources.derived:`
#
# A git-ignored file the build or start command writes on every run is not a
# source: a clean checkout regenerates it. Whether a command writes a file
# cannot be read off the command line, and running the build to find out is
# not a check's job, so the project declares them — a list of globs, matched
# against the worktree-relative path (`*` crosses `/`):
#
#   ignoredSources:
#     derived:
#       - "brainstorm/index.html"     # written by brainstorm.ts on every start
#       - "brainstorm/*.js"
#
# A declared path is never reported, listed or sibling. The per-folder rule
# above narrowed the false alarm; it could not remove it, because a plan that
# lists brainstorm/foo.html still makes brainstorm/index.html a sibling of the
# same extension (a client's LVI-057).
#
# Read by lv-registry-update.sh's `active -> verify` guard, and by /lv-test
# before it removes a worktree.
#
# Exit 0 — nothing ignored.
# Exit 1 — ignored sources; one per line on stdout, `<path>\t<source:line:pattern>`.
# Exit 2 — usage, or the plan cannot be resolved.
# Exit 3 — the plan has no worktree (nothing on disk to lose, nothing to check).

set -uo pipefail

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lv-orch-lib.sh
source "$SELF_DIR/lv-orch-lib.sh"

usage() { sed -n '2,56p' "$0" >&2; }

raw="${1:-}"
case "$raw" in
  ""|-h|--help) usage; [ -n "$raw" ] && exit 0 || exit 2 ;;
esac
shift
wt=""
while [ $# -gt 0 ]; do
  case "$1" in
    --worktree) wt="${2:?--worktree requires a path}"; shift 2 ;;
    *) echo "lv-ignored-sources: unknown argument: $1" >&2; exit 2 ;;
  esac
done

plan_id=$(printf '%s' "$raw" | grep -oE "^($LV_PLN_RE)-[0-9]+" || true)
[ -n "$plan_id" ] || { echo "lv-ignored-sources: not a plan ID: $raw" >&2; exit 2; }

root="$(wf_develop_root)"
slug=$(wf_registry_field "$plan_id" slug "$root/plans/REGISTRY.md")
plan_md="$root/plans/${plan_id}-${slug}/plan.md"
[ -n "$slug" ] && [ -f "$plan_md" ] || { echo "lv-ignored-sources: no plan.md for $plan_id" >&2; exit 2; }

if [ -z "$wt" ]; then
  branch=$(wf_registry_field "$plan_id" branch "$root/plans/REGISTRY.md")
  # The Branch column is often "—" even while the worktree is live, so fall
  # back to the branch every plan is cut on, as lv-list-completable.sh does.
  # Exit 3 on a worktree that exists sent eleven reports' worth of /lv-test
  # runs into removal unchecked.
  case "$branch" in ""|"—"|"-") branch="feature/${plan_id}-${slug}" ;; esac
  wt=$(cd "$root" && wf_worktree_for_branch "$branch")
fi
if [ -z "$wt" ] || [ ! -d "$wt" ]; then
  echo "lv-ignored-sources: $plan_id has no worktree — nothing to check" >&2
  exit 3
fi

files=$(wf_plan_files "$plan_md")
[ -n "$files" ] || exit 0

# "<dir>\t<.ext>" for every listed path with an extension.
dir_exts=$(printf '%s\n' "$files" | awk '{ n = $0; d = ""; j = match(n, /\/[^\/]*$/); if (j > 0) { d = substr(n, 1, j - 1); n = substr(n, j + 1) }
  i = match(n, /\.[^.]+$/); if (i > 1) print d "\t" substr(n, i) }' | sort -u)

derived=$(wf_cfg_list ignoredSources.derived)

found=$(
  cd "$wt" || exit 0
  # Declared in levain.yml as regenerated by the build or start (LVI-057).
  is_derived() {
    local g
    [ -n "$derived" ] || return 1
    while IFS= read -r g; do
      [ -n "$g" ] || continue
      # shellcheck disable=SC2053  # the glob is meant to match unquoted
      [[ "$1" == $g ]] && return 0
    done <<< "$derived"
    return 1
  }
  ignored() { ! git ls-files --error-unmatch -- "$1" >/dev/null 2>&1 && git check-ignore -q -- "$1" 2>/dev/null; }
  # What the harness itself installs into a worktree is ignored by design and
  # was never the plan's to write (scripts/lv-exec.sh beside a plan's
  # scripts/*.sh read as a lost source and refused active -> verify).
  harness() {
    case "$1" in
      (scripts/lv-exec.sh|scripts/wf-exec.sh|scripts/version-map.txt|scripts/current|scripts/v[0-9]*/*|scripts/gen/*) return 0 ;;
      (.claude/workflow.md|.claude/workflow-*|.claude/skills/lv-*|.plan-ref) return 0 ;;
    esac
    return 1
  }
  printf '%s\n' "$files" | while IFS= read -r p; do
    [ -n "$p" ] || continue
    if [ -f "$p" ] && ! harness "$p" && ! is_derived "$p" && ignored "$p"; then printf '%s\n' "$p"; fi
    d="${p%/*}"
    [ "$d" != "$p" ] && [ -d "$d" ] || continue
    exts=$(printf '%s\n' "$dir_exts" | awk -F'\t' -v d="$d" '$1 == d { print $2 }')
    [ -n "$exts" ] || continue
    git ls-files --others --ignored --exclude-standard -- "$d" 2>/dev/null \
      | awk -v d="$d/" 'index($0, d) == 1 && index(substr($0, length(d) + 1), "/") == 0' \
      | while IFS= read -r f; do
          harness "$f" && continue
          is_derived "$f" && continue
          [ "${f##*.}" != "$f" ] && printf '%s\n' "$exts" | grep -qxF ".${f##*.}" && printf '%s\n' "$f"
        done
  done | sort -u
)

[ -n "$found" ] || exit 0
printf '%s\n' "$found" | while IFS= read -r f; do
  rule=$(cd "$wt" && git check-ignore -v -- "$f" 2>/dev/null | cut -f1)
  printf '%s\t%s\n' "$f" "${rule:-ignored}"
done
exit 1
